// ---------------------------------------------------------------------------
// Admin dashboard trend data — new signups and quiz attempts per day, for
// the last N days (oldest first). Days with zero of either are included
// with a 0 count, so the chart's x-axis has no gaps.
// ---------------------------------------------------------------------------

export interface DailyCounts {
  date: string; // YYYY-MM-DD
  signups: number;
  attempts: number;
}

/** Aggregate-only counts safe to show on the public landing page. */
export function getPublicCommunityStats(): { totalUsers: number; totalAttempts: number } {
  const totalUsers = (db.prepare("SELECT COUNT(*) AS n FROM users WHERE role = 'user'").get() as { n: number }).n;
  const totalAttempts = (db.prepare("SELECT COUNT(*) AS n FROM quiz_attempts").get() as { n: number }).n;
  return { totalUsers, totalAttempts };
}

export function getDailyTrend(days: number): DailyCounts[] {
  const since = new Date();
  since.setDate(since.getDate() - (days - 1));
  const sinceDate = since.toISOString().slice(0, 10);

  const signupRows = db
    .prepare(
      `SELECT substr(created_at, 1, 10) AS date, COUNT(*) AS n FROM users
       WHERE substr(created_at, 1, 10) >= ? GROUP BY date`
    )
    .all(sinceDate) as { date: string; n: number }[];
  const attemptRows = db
    .prepare(
      `SELECT substr(created_at, 1, 10) AS date, COUNT(*) AS n FROM quiz_attempts
       WHERE substr(created_at, 1, 10) >= ? GROUP BY date`
    )
    .all(sinceDate) as { date: string; n: number }[];

  const signupsByDate = new Map(signupRows.map((r) => [r.date, r.n]));
  const attemptsByDate = new Map(attemptRows.map((r) => [r.date, r.n]));

  const out: DailyCounts[] = [];
  for (let i = 0; i < days; i++) {
    const d = new Date(since);
    d.setDate(d.getDate() + i);
    const date = d.toISOString().slice(0, 10);
    out.push({ date, signups: signupsByDate.get(date) ?? 0, attempts: attemptsByDate.get(date) ?? 0 });
  }
  return out;
}

