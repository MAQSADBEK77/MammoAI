function slugify(title: string): string {
  return (
    title
      .toLowerCase()
      .trim()
      .replace(/['"]/g, "")
      .replace(/[^a-z0-9Ѐ-ӿ]+/g, "-")
      .replace(/^-+|-+$/g, "") || randomUUID().slice(0, 8)
  );
}

export function createArticle(input: {
  title: string;
  excerpt: string;
  content: string;
  published: boolean;
  videoUrl?: string;
}): Article {
  let slug = slugify(input.title);
  if (getArticleBySlug(slug)) slug = `${slug}-${randomUUID().slice(0, 4)}`;
  const article: Article = {
    id: randomUUID(),
    slug,
    title: input.title,
    excerpt: input.excerpt,
    content: input.content,
    published: input.published,
    videoUrl: input.videoUrl ?? "",
    createdAt: new Date().toISOString(),
  };
  db.prepare(
    `INSERT INTO articles (id, slug, title, excerpt, content, published, created_at, video_url) VALUES (@id, @slug, @title, @excerpt, @content, @published, @createdAt, @videoUrl)`
  ).run({ ...article, published: article.published ? 1 : 0 });
  return article;
}

